def get_question_for_day(day_key: str) -> dict:
    """
    Returns a deterministic question based on the day_key string (e.g. "2026-11-20").
    Ensures both partners always get the identical question for that calendar day.
    """
    # Calculate a hash-based index from day_key
    total_val = sum(ord(c) for c in day_key)
    index = total_val % len(SPARK_QUESTIONS)
    return SPARK_QUESTIONS[index]
